"""
ORION OpenSCENARIO 2.0 Exporter.  [Phase 4]

Converts AREP ScenarioDefinition objects to OpenSCENARIO 2.0 DSL (.osc)
format, enabling interoperability with CARLA, ASAM member tools,
and customer scenario libraries.

This writes the subset of OSC2 that `OpenSCENARIOImporter` reads back — it
is not a general OSC2 generator, and the output is checked against ORION's
own reader, not against a conforming OSC2 implementation.

AREP → OSC2 mapping:
  ScenarioDefinition.name              → scenario name declaration
  duration                             → do parallel(duration: …s)
  parameterization ranges              → `name: float` + keep(name in [a .. b])
  parameterization scalars             → `name: float = v`
  traffic NPC entries                  → actor Vehicle / Pedestrian / Truck / Bicycle
  initial x / y / heading / velocity   → assign_position / assign_orientation /
                                         assign_speed
  trigger_type / trigger_value         → wait time / ttc / distance condition
  constant_velocity BT                 → drive action
  hesitant_brake BT                    → brake action with deceleration
  pedestrian behaviours                → walk action

Everything else ORION carries — the remaining behaviour parameters, other
bt_type trees, events, road template, weather, constraints, termination — has
no OSC2 equivalent. It is written once, as a ``#@orion`` annotation line: a
comment to every other OSC2 tool, read back by ORION's importer. Each field is
encoded exactly once, so the OSC2 constructs and the annotations can never
disagree about the same value.
"""

from __future__ import annotations

import dataclasses
import json
from pathlib import Path
from typing import Any, Dict, List, Tuple

from arep.scenario.schema import ScenarioDefinition, TrafficObjectDefinition
from arep.utils.logging_config import get_logger

logger = get_logger("scenario.osc_exporter")

# The marker both sides agree on. A comment to OSC2; data to ORION.
ANNOTATION = "#@orion"

# Separator for a nested parameterization path flattened into one OSC2
# identifier: npc_overrides.lead_vehicle.initial_x becomes
# npc_overrides__lead_vehicle__initial_x. A path component containing "__"
# would make that ambiguous, so export refuses it rather than guess.
PARAM_SEPARATOR = "__"

# ScenarioDefinition fields written as OSC2 constructs (or as their own
# annotation, for events). Every other field goes in the scenario annotation,
# so a field added to the schema later round-trips without touching this file.
OSC2_FIELDS = frozenset(
    {"duration", "ego_initial", "traffic_objects", "events", "parameterization"}
)

# ORION object type → OSC2 actor type. The importer holds the inverse.
ACTOR_TYPES = {
    "car": "Vehicle",
    "pedestrian": "Pedestrian",
    "truck": "Truck",
    "bicycle": "Bicycle",
}

# OSC2 action → the behaviour (and bt_type) ORION's importer gives it.
VERB_BEHAVIOUR = {
    "drive": ("constant_velocity", None),
    "brake": ("reactive_vehicle", "hesitant_brake"),
    "walk": ("pedestrian", None),
}


class OpenSCENARIOExporter:
    """
    Converts ScenarioDefinition to OpenSCENARIO 2.0 DSL string.
    """

    def export(self, scenario: ScenarioDefinition) -> str:
        """
        Convert a ScenarioDefinition to an OpenSCENARIO 2.0 .osc string.

        Raises:
            ValueError: a parameterization entry cannot be written as an OSC2
                parameter (a non-identifier name, or a non-numeric value).
                Refused rather than dropped: losing a range turns a
                parameterised scenario into one fixed setting, which still
                runs and still scores.
        """
        lines: List[str] = [
            "# Generated by ORION from an AREP ScenarioDefinition.",
            f"# Lines beginning {ANNOTATION!r} carry ORION fields that have no",
            "# OpenSCENARIO 2.0 equivalent. Other OSC2 tools read them as comments;",
            "# ORION's importer reads them back.",
            "",
            "import basic.osc",
            "",
            f"scenario {_identifier(scenario.name)}:",
            f"    {ANNOTATION} scenario {_json(_scenario_fields(scenario))}",
        ]

        params = self._parameter_block(scenario)
        if params:
            lines.append("")
            lines += params

        lines.append("")
        lines.append("    ego: Vehicle")
        for obj in scenario.traffic_objects:
            actor_type = ACTOR_TYPES.get(obj.type, "Vehicle")
            lines.append(f"    {_identifier(obj.id)}: {actor_type}")
        lines.append("")

        lines.append(f"    do parallel(duration: {_num(scenario.duration)}s):")
        lines.append("        serial:")
        lines += _initial_state("ego", scenario.ego_initial, "            ")
        lines.append("            ego.drive()")

        for obj in scenario.traffic_objects:
            lines.append("")
            lines += self._actor_act(obj)

        for event in scenario.events:
            lines.append(f"    {ANNOTATION} event {_json(dataclasses.asdict(event))}")
        return "\n".join(lines) + "\n"

    def export_to_file(self, scenario: ScenarioDefinition, output_path: str) -> None:
        """Export to a .osc file, creating the directory if needed."""
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.export(scenario), encoding="utf-8")
        logger.info("Exported scenario to %s", path)

    # ── Internals ────────────────────────────────────────────────────

    @staticmethod
    def _parameter_block(scenario: ScenarioDefinition) -> List[str]:
        """Parameterisation becomes OSC2 parameter fields with keep() ranges."""
        lines: List[str] = []
        for path, spec in _flatten_ranges(scenario.parameterization):
            for part in path:
                if not part.isidentifier() or PARAM_SEPARATOR in part:
                    raise ValueError(
                        f"parameterization key {'.'.join(path)!r} cannot be "
                        f"written as an OSC2 parameter: {part!r} is not an "
                        f"identifier without {PARAM_SEPARATOR!r}"
                    )
            name = PARAM_SEPARATOR.join(path)
            if isinstance(spec, dict):
                low, high = spec["min"], spec["max"]
                kind = "int" if _is_int(low) and _is_int(high) else "float"
                lines.append(f"    {name}: {kind}")
                lines.append(f"    keep({name} in [{_num(low)} .. {_num(high)}])")
            else:
                kind = "int" if _is_int(spec) else "float"
                lines.append(f"    {name}: {kind} = {_num(spec)}")
        return lines

    def _actor_act(self, obj: TrafficObjectDefinition) -> List[str]:
        """One NPC to a serial block: initial state, trigger, action."""
        name = _identifier(obj.id)
        behaviour = obj.behavior.type
        params = dict(obj.behavior.parameters or {})

        if params.get("bt_type") == "hesitant_brake":
            verb = "brake"
        elif behaviour in ("pedestrian", "reactive_pedestrian"):
            verb = "walk"
        else:
            verb = "drive"
        implied_behaviour, implied_bt = VERB_BEHAVIOUR[verb]
        if implied_bt is not None:
            params.pop("bt_type")

        lines = ["        serial:"]
        lines += _initial_state(name, obj.initial, "            ")

        trigger = _trigger_clause(params)
        if trigger:
            params.pop("trigger_type")
            params.pop("trigger_value")

        decel: Any = params.get("final_decel")
        modifiers: List[str] = []
        if verb == "brake" and _is_number(decel) and decel <= 0:
            # OSC2 states deceleration as a magnitude; ORION signs it.
            modifiers.append(f"deceleration({_num(abs(decel))}mpsps)")
            params.pop("final_decel")

        # Whatever OSC2 could not say goes in one annotation, exactly once.
        annotation: Dict[str, Any] = {}
        if name != obj.id:
            annotation["id"] = obj.id
        if ACTOR_TYPES.get(obj.type) is None:
            annotation["type"] = obj.type
        if behaviour != implied_behaviour:
            annotation["behavior"] = behaviour
        if params:
            annotation["parameters"] = params
        if annotation:
            if behaviour != implied_behaviour:
                lines.append(
                    f"            # ORION behaviour {behaviour!r}"
                    + (f" / {params['bt_type']!r}" if "bt_type" in params else "")
                    + f" has no OSC2 equivalent; {verb}() approximates it."
                )
            lines.append(f"            {ANNOTATION} actor {name} {_json(annotation)}")

        if trigger:
            lines.append(f"            wait {trigger}")
        lines.append(f"            {name}.{verb}()" + (" with:" if modifiers else ""))
        lines += [f"                {m}" for m in modifiers]
        return lines


def _initial_state(name: str, initial, indent: str) -> List[str]:
    return [
        f"{indent}{name}.assign_position(position_3d("
        f"x: {_num(initial.x)}m, y: {_num(initial.y)}m, z: 0.0m))",
        f"{indent}{name}.assign_orientation(orientation_3d("
        f"yaw: {_num(initial.heading)}rad))",
        f"{indent}{name}.assign_speed({_num(initial.velocity)}mps)",
    ]


def _trigger_clause(params: dict) -> str:
    trigger_type = params.get("trigger_type")
    value = params.get("trigger_value")
    if not _is_number(value):
        return ""
    if trigger_type == "time":
        return f"elapsed({_num(value)}s)"
    if trigger_type == "ttc":
        return f"time_to_collision(ego) < {_num(value)}s"
    if trigger_type == "proximity":
        return f"distance_to(ego) < {_num(value)}m"
    return ""


def _scenario_fields(scenario: ScenarioDefinition) -> Dict[str, Any]:
    """Every ScenarioDefinition field OSC2 has no construct for."""
    out: Dict[str, Any] = {}
    for f in dataclasses.fields(scenario):
        if f.name in OSC2_FIELDS:
            continue
        value: Any = getattr(scenario, f.name)
        is_instance = dataclasses.is_dataclass(value) and not isinstance(value, type)
        out[f.name] = dataclasses.asdict(value) if is_instance else value
    return out


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=True)


def _num(value: Any) -> str:
    """Shortest text that reads back as the same number (repr round-trips)."""
    return repr(int(value)) if _is_int(value) else repr(float(value))


def _is_int(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _identifier(text: str) -> str:
    """A safe OSC2 identifier: letters, digits and underscores only."""
    cleaned = "".join(ch if ch.isalnum() else "_" for ch in str(text)).strip("_")
    if not cleaned:
        return "unnamed"
    return cleaned if cleaned[0].isalpha() else f"s_{cleaned}"


def _flatten_ranges(node, prefix: Tuple[str, ...] = ()):
    """Yield (path, spec) for each range or scalar in a parameter block.

    Raises on anything else rather than skipping it — see `export`.
    """
    if isinstance(node, dict):
        if "min" in node and "max" in node:
            if not (_is_number(node["min"]) and _is_number(node["max"])):
                raise ValueError(f"non-numeric range at {'.'.join(prefix)!r}")
            if set(node) != {"min", "max"}:
                raise ValueError(
                    f"range at {'.'.join(prefix)!r} carries keys OSC2 keep() "
                    f"cannot express: {sorted(set(node) - {'min', 'max'})}"
                )
            yield prefix, node
            return
        for key, value in node.items():
            yield from _flatten_ranges(value, prefix + (str(key),))
        return
    if not _is_number(node):
        raise ValueError(
            f"parameterization value at {'.'.join(prefix)!r} is {node!r}; "
            "only numbers and {min, max} ranges can be OSC2 parameters"
        )
    yield prefix, node
